def _lane_root(field: ProtocolField, document: dict[str, Any]) -> Reading:
    """The node a field's pointer is relative to."""
    if field.lane is Lane.DOCUMENT:
        return Reading(value=document)

    body = read_pointer(document, _LANE_POINTERS[field.lane])
    if isinstance(body, _Absent):
        return Reading()

    if field.lane not in (Lane.MESSAGE_SIGNED, Lane.NOTE_SIGNED):
        return Reading(value=body)

    lane = resolve_signed_lane(body)
    if lane.problem:
        return lane
    node = lane.value
    if not isinstance(node, dict):  # pragma: no cover - resolver guarantees it
        return Reading(problem="imzali lane okunamadi")
    if field.derived is Derived.SIGNED_REQUIRED:
        return Reading(value=node)
    return Reading(value=node["properties"])


def _read(field: ProtocolField, document: dict[str, Any]) -> Reading:
    """Read the value a field describes, including the derived ones."""
    root = _lane_root(field, document)
    if root.problem or isinstance(root.value, _Absent):
        return root

    if field.derived is Derived.LANE_PRESENT:
        return Reading(value=field.expected if isinstance(root.value, dict) else ABSENT)

    if field.derived is Derived.SIGNED_REQUIRED:
        node = root.value
        if not isinstance(node, dict):  # pragma: no cover - guaranteed above
            return Reading()
        required = node.get("required")
        return Reading() if required is None else Reading(value=required)

    value = read_pointer(root.value, field.pointer)
    if (
        field.compare is Compare.PROSE
        and isinstance(value, str)
        and len(sweep_untrusted(value)) > MAX_PROSE_CHARS
    ):
        return Reading(problem="aciklama beklenenden cok uzun, degerlendirilmedi")
    return Reading(value=value)


def _observe(
    field: ProtocolField, documents: dict[SourceId, dict[str, Any]]
) -> FieldObservation:
    document = documents.get(field.source_id)
    if document is None:
        return FieldObservation(
            field=field, observed=MISSING, outcome=FieldOutcome.MISSING
        )

    reading = _read(field, document)
    if reading.problem:
        return FieldObservation(
            field=field,
            observed=safe_display(reading.value),
            outcome=FieldOutcome.UNSUPPORTED,
            problem=reading.problem,
        )
    if isinstance(reading.value, _Absent):
        return FieldObservation(
            field=field, observed=MISSING, outcome=FieldOutcome.MISSING
        )

    outcome = (
        FieldOutcome.MATCHED if _compare(field, reading.value) else FieldOutcome.MISMATCH
    )
    return FieldObservation(
        field=field, observed=safe_display(reading.value), outcome=outcome
    )


def project(documents: dict[SourceId, dict[str, Any]]) -> ProjectionResult:
    """Compare the live documents with the expected contract.

    ``documents`` holds only the sources that parsed. Three outcomes:

    * a critical field present and different is **drift**;
    * a critical field that could not be read is **unavailable** - the check
      did not complete, and saying more than that would be a claim about the
      server that the evidence does not support;
    * otherwise **current**, with any warnings listed beside it.

    Drift wins over unavailable: a real, readable change is the more specific
    answer and the more useful one. Either way ``manifest_current`` is false.
    """
    observations = tuple(_observe(field, documents) for field in PROTOCOL_FIELDS)

    mismatches = [item for item in observations if item.is_critical_mismatch]
    if mismatches:
        return ProjectionResult(
            state=DriftState.DRIFTED,
            observations=observations,
            reasons=tuple(item.reason for item in mismatches),
        )

    unevaluable = [item for item in observations if item.is_critical_unevaluable]
    if unevaluable:
        return ProjectionResult(
            state=DriftState.UNAVAILABLE,
            observations=observations,
            reasons=tuple(item.reason for item in unevaluable),
        )

    return ProjectionResult(
        state=DriftState.CURRENT, observations=observations, reasons=()
    )


def unavailable(reasons: tuple[str, ...]) -> ProjectionResult:
    """A verdict for a check that could not be completed."""
    return ProjectionResult(
        state=DriftState.UNAVAILABLE, observations=(), reasons=reasons
    )


