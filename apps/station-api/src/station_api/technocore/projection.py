def sweep_untrusted(text: str) -> str:
    """Replace invisible characters with a space. No truncation.

    Used before *scanning* a remote description, where a marker hiding past a
    display limit would matter. Display uses :func:`safe_display`.
    """
    return "".join(
        " " if unicodedata.category(character) in _INVISIBLE else character
        for character in text
    )


def safe_display(value: object) -> str:
    """Make a remote value safe to store, log and render.

    Control, format and separator characters become a space, and the result is
    truncated. Level-1 authority means the document is probably accurate; it
    does not mean the bytes are safe to paste into a log line or a UI.

    This is a **display** function. Nothing compares its output: sweeping and
    stripping would make a payload with a trailing newline equal to the
    canonical one, and it is not.
    """
    if isinstance(value, _Absent):
        return MISSING
    if value is None:
        return "null"
    if isinstance(value, bool):
        return "true" if value else "false"
    text = (
        ",".join(safe_display(item) for item in value)
        if isinstance(value, list)
        else str(value)
    )

    swept = sweep_untrusted(text).strip()
    if len(swept) > MAX_OBSERVED_CHARS:
        return swept[:MAX_OBSERVED_CHARS] + "..."
    return swept


def _prose_matches(value: str, expected: str) -> bool:
    """Every machine token present as a word, and no negation anywhere."""
    lowered = sweep_untrusted(value).lower()
    if any(
        re.search(rf"\b{re.escape(marker)}\b", lowered) for marker in NEGATION_MARKERS
    ):
        return False
    return all(
        re.search(rf"\b{re.escape(token)}\b", lowered) for token in expected.split()
    )


def _compare(field: ProtocolField, value: object) -> bool:
    """Type-checked comparison against the original value."""
    expected = field.expected

    if field.compare is Compare.TEXT:
        return isinstance(value, str) and value == expected
    if field.compare is Compare.NUMBER:
        # bool is an int subclass and True == 1; a published `true` is not 1.
        return (
            isinstance(value, int) and not isinstance(value, bool) and value == expected
        )
    if field.compare is Compare.MEMBER:
        return isinstance(value, list) and any(
            isinstance(item, str) and item == expected for item in value
        )
    if field.compare is Compare.NAME_SET:
        if not isinstance(value, list) or not all(
            isinstance(item, str) for item in value
        ):
            return False
        return isinstance(expected, tuple) and set(value) == set(expected)
    if field.compare is Compare.PROSE:
        return (
            isinstance(value, str)
            and isinstance(expected, str)
            and _prose_matches(value, expected)
        )
    # Exhaustive. A new comparison mode fails type-checking here rather than
    # silently defaulting to "matches" or "does not match".
    assert_never(field.compare)


