"""The critical protocol projection, and drift against it.

A raw hash of ``/openapi.json`` would flag every typo fix as protocol drift
and would therefore be ignored within a week. What matters is narrower: the
handful of machine-readable facts a signature's validity depends on. This
module names them, states where each one lives, says why it is critical, and
compares the live value against what Station signs for.

Where the signed lane actually lives
------------------------------------
The reference does **not** publish the ``sig`` and ``nonce`` constraints on
``schema.properties``. It hangs them off ``did``::

    schema.dependentSchemas.did = {
        "required": ["sig", "nonce"],
        "properties": {"sig": {...}, "nonce": {...}},
    }

and leaves ``properties.sig`` carrying nothing but a ``description``. The
reference explains why: a body with no ``did`` is an ordinary unsigned write,
and ``sig``/``nonce`` on one are ignored rather than validated, so publishing
their patterns unconditionally would document a constraint nothing enforces.

Stage 3 read them from ``properties`` and therefore found nothing, which is
the false "the server changed the signature format" alarm this module now
exists to not repeat. Every pointer below is verified against documents
generated by the pinned reference itself - see
``tests/security/technocore_reference/PROVENANCE.md``.

A schema is read as a whole, or not at all
------------------------------------------
Finding the right value somewhere in a schema does not establish that the
schema accepts our request. Keywords at one level are conjunctive, so a
constraint we did not read still applies - and three documents that reject
every signed write once reported "current" because of exactly that. The
keyword lists below are therefore **allow-lists**: a key this module cannot
read makes the schema unevaluable rather than invisible. See the block above
:data:`ANNOTATION_KEYS` for the three cases and why they passed.

Being absent is not the same as being different
-----------------------------------------------
A field the document does not carry, and a schema shape this module does not
understand, are both reported as *unevaluable* rather than as drift. Both keep
the gate shut - the verdict is fail-closed either way - but the reason the
user reads is "protocol conformance could not be verified" rather than a claim
about what the server did. Stating "every signature will be rejected" on the
strength of a lookup that went to the wrong place is exactly the mistake that
made this module wrong the first time.

Expectations come from our own contract
---------------------------------------
The patterns are derived from :mod:`technocore_conform`, the engine that
actually signs. Copying them out of the live document would make the check
self-fulfilling: it would report "current" forever and detect nothing.

Remote values are untrusted input
---------------------------------
Authority level 1 buys accuracy, not safety. Every observed value is
truncated and stripped of control characters *for display*. The comparison
itself runs against the original, type-checked value, so a padded or
whitespace-decorated payload cannot be normalised into a match.
"""

