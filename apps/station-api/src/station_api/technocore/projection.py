class Derived(StrEnum):
    """Fields computed from a lane rather than read at a pointer."""

    #: The lane exists at the method and path Station will use.
    LANE_PRESENT = "lane_present"
    #: The set of field names the signed lane makes *required*.
    SIGNED_REQUIRED = "signed_required"


