@dataclass(frozen=True, slots=True)
class FieldObservation:
    """The verdict for one field."""

    field: ProtocolField
    observed: str
    outcome: FieldOutcome
    #: Set when the outcome is ``UNSUPPORTED``; explains what was not read.
    problem: str = ""

    @property
    def matches(self) -> bool:
        return self.outcome is FieldOutcome.MATCHED

    @property
    def is_critical_failure(self) -> bool:
        return not self.matches and self.field.severity is Severity.CRITICAL

    @property
    def is_critical_mismatch(self) -> bool:
        """A critical field that is present and genuinely different."""
        return (
            self.outcome is FieldOutcome.MISMATCH
            and self.field.severity is Severity.CRITICAL
        )

    @property
    def is_critical_unevaluable(self) -> bool:
        """A critical field we could not read. Not evidence of a change."""
        return (
            self.outcome in (FieldOutcome.MISSING, FieldOutcome.UNSUPPORTED)
            and self.field.severity is Severity.CRITICAL
        )

    @property
    def reason(self) -> str:
        """One line saying what happened, without overclaiming."""
        label = self.field.label
        if self.outcome is FieldOutcome.MISMATCH:
            return (
                f"{label}: beklenen {self.field.expected_display!r}, "
                f"gorulen {self.observed!r}"
            )
        if self.outcome is FieldOutcome.MISSING:
            return (
                f"{label}: belgede bulunamadi ({self.field.json_path}); "
                "protokol uyumu dogrulanamadi"
            )
        if self.outcome is FieldOutcome.UNSUPPORTED:
            return (
                f"{label}: sema bicimi okunamadi ({self.problem}); "
                "protokol uyumu dogrulanamadi"
            )
        return ""


@dataclass(frozen=True, slots=True)
class ProjectionResult:
    """The outcome of comparing the live documents with the expectation."""

    state: DriftState
    observations: tuple[FieldObservation, ...]
    #: Human-readable reasons the state is not ``current``.
    reasons: tuple[str, ...]

    @property
    def critical_mismatches(self) -> tuple[FieldObservation, ...]:
        """Critical fields that are present and different: real drift."""
        return tuple(item for item in self.observations if item.is_critical_mismatch)

    @property
    def critical_unevaluable(self) -> tuple[FieldObservation, ...]:
        """Critical fields that could not be read at all."""
        return tuple(item for item in self.observations if item.is_critical_unevaluable)

    @property
    def critical_failures(self) -> tuple[FieldObservation, ...]:
        """Every critical field that did not match, whatever the reason."""
        return tuple(item for item in self.observations if item.is_critical_failure)

    @property
    def warnings(self) -> tuple[FieldObservation, ...]:
        return tuple(
            item
            for item in self.observations
            if not item.matches and item.field.severity is Severity.WARNING
        )


