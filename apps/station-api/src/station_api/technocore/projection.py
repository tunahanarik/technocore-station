# ---------------------------------------------------------------------------
# What this module claims to understand about a schema
#
# The first version of this check named the keywords it refused - $ref, allOf,
# not, and so on - and read the ones it wanted from whatever was left. That is
# backwards, and it let three different schemas that reject every signed
# request report "current":
#
#   * ``not: {}`` inside the ``sig`` field node. The pattern and the lengths
#     were still correct, and still read, while the node as a whole matched
#     nothing at all.
#   * ``properties.sig.maxLength: 1`` unconditionally, beside the conditional
#     ``minLength: 86``. Keywords at a level are conjunctive, so both apply and
#     no string satisfies both; only the conditional one was being read.
#   * ``anyOf: [{"not": {"required": ["did"]}}]`` on the body, which forbids
#     the very field that selects the signed lane. ``anyOf`` was allowed by
#     name, on the reasoning that it could only add a constraint - true, and
#     beside the point, because a constraint it adds can reject us.
#
# The shared mistake: finding the right value somewhere does not establish
# that the schema accepts our request. So the lists below are **allow-lists**.
# A key that is not named here is not ignored - it makes the schema
# unevaluable, and the gate shuts. This is not a JSON Schema engine and does
# not try to be one; it is an explicit statement of the shapes it can read.
# ---------------------------------------------------------------------------

#: Keys that annotate and never constrain. A change to one of these is
#: documentation drift, so they are stripped before a node is judged and can
#: never raise a protocol alarm.
ANNOTATION_KEYS: Final = frozenset(
    {
        "$comment",
        "default",
        "deprecated",
        "description",
        "example",
        "examples",
        "readOnly",
        "title",
        "writeOnly",
    }
)

#: Understood on a request-body schema.
UNDERSTOOD_BODY_KEYS: Final = frozenset(
    {"type", "properties", "required", "anyOf", "dependentSchemas"}
)

#: Understood on the ``dependentSchemas.did`` node.
UNDERSTOOD_LANE_KEYS: Final = frozenset({"type", "properties", "required"})

#: Understood on a single field's schema (``sig``, ``nonce``, ``did``). Their
#: *values* are type-checked by the projected fields themselves - a
#: ``maxLength`` of ``"86"`` is a mismatch on ``signature_max_length`` - so
#: this list is only about which keywords may appear at all.
UNDERSTOOD_FIELD_KEYS: Final = frozenset({"type", "pattern", "minLength", "maxLength"})

#: Understood inside one ``anyOf`` branch.
UNDERSTOOD_BRANCH_KEYS: Final = frozenset({"required"})

#: The fields a signed request body carries. Used to decide whether an
#: ``anyOf`` branch is one a signed body can satisfy. ``from`` is absent on
#: purpose: the reference ignores it on the signed lane, so Station does not
#: have to send it and must not depend on a branch that requires it.
_SIGNED_BODY_FIELDS: Final = frozenset({"did", "sig", "nonce"})

#: Words that deny a contract rather than restate it. A description is not
#: accepted merely because the right words appear in it: "86 characters, but
#: no longer unpadded" contains every token and means the opposite.
#:
#: The list is closed and short on purpose, and it is checked against the real
#: pinned description, which says "Re-encode the raw signature *rather than*
#: editing its tail" - so "rather than" is not a marker. Neither are "no" or
#: "without", because "no padding" is a legitimate way to say unpadded.
#: ``padded`` is matched on a word boundary, which "unpadded" does not create.
NEGATION_MARKERS: Final[tuple[str, ...]] = (
    "not",
    "never",
    "no longer",
    "instead",
    "deprecated",
    "obsolete",
    "removed",
    "padded",
)


def read_pointer(document: object, segments: tuple[str, ...]) -> object:
    """Walk explicit segments. Returns :data:`ABSENT` if any is missing."""
    current: object = document
    for segment in segments:
        if not isinstance(current, dict) or segment not in current:
            return ABSENT
        current = current[segment]
    return current


def pointer_text(segments: tuple[str, ...]) -> str:
    """The segments as a JSON Pointer, for display and for the record."""
    escaped = (segment.replace("~", "~0").replace("/", "~1") for segment in segments)
    return "/" + "/".join(escaped)


@dataclass(frozen=True, slots=True)
class Reading:
    """A value read from a document, or the reason it could not be.

    ``problem`` and ``conflict`` are deliberately different answers:

    * **problem** - the schema carries something this module cannot evaluate.
      We are not entitled to say what the server did, only that we could not
      check it. Reported as ``unsupported``.
    * **conflict** - the schema was evaluated and the constraints it publishes
      contradict each other, so no request can satisfy them. That is a real,
      demonstrated finding about the document. Reported as ``mismatch``.

    Both shut the gate. The split exists so the sentence the user reads is
    true, which is the whole reason this module was rewritten once already.
    """

    value: object = ABSENT
    #: Non-empty when the shape could not be evaluated. -> unsupported
    problem: str = ""
    #: Non-empty when the shape was evaluated and contradicts itself.
    #: -> mismatch
    conflict: str = ""


@dataclass(frozen=True, slots=True)
class SignedBodyView:
    """The parts of a request-body schema a signed write has to satisfy."""

    #: The body schema itself.
    body: dict[str, Any]
    #: The ``dependentSchemas.did`` node - what applies once a did is present.
    lane: dict[str, Any]
    #: ``lane["properties"]`` - the credential field schemas.
    credentials: dict[str, Any]


def _unknown_keys(node: dict[str, Any], understood: frozenset[str]) -> list[str]:
    """Keys that are neither understood nor pure annotation."""
    return sorted(set(node) - understood - ANNOTATION_KEYS)


def _constraints(node: dict[str, Any]) -> dict[str, Any]:
    """A field node with its annotations removed."""
    return {key: value for key, value in node.items() if key not in ANNOTATION_KEYS}


def _check_field_node(node: object, where: str) -> Reading:
    """A single field's schema carries only keywords we can read.

    This is what stops ``"sig": {"pattern": ..., "not": {}}`` from passing.
    The pattern is right there and correct; the node still matches nothing.
    """
    if not isinstance(node, dict):
        return Reading(problem=f"{where} bir nesne degil")
    unknown = _unknown_keys(node, UNDERSTOOD_FIELD_KEYS)
    if unknown:
        return Reading(
            problem=f"{where} degerlendirilemeyen anahtar tasiyor: {', '.join(unknown)}"
        )
    return Reading(value=node)


def _bound(node: dict[str, Any], key: str) -> int | None:
    """A length bound, only when it is really a number."""
    value = node.get(key)
    if isinstance(value, bool) or not isinstance(value, int):
        return None
    return value


def _reconcile(
    unconditional: object, conditional: dict[str, Any], where: str
) -> Reading:
    """Constraints published at both levels apply to the same value together.

    The reference publishes ``properties.sig`` carrying a description and
    nothing else, so the usual answer is "nothing to reconcile". When the
    unconditional node does carry constraints, they are not an alternative to
    the conditional ones - both apply - and this is where ``maxLength: 1``
    beside a conditional ``minLength: 86`` is caught.

    Only three outcomes are possible, and none of them intersects regexes or
    computes a general schema conjunction:

    * an identical, repeated constraint is fine;
    * length bounds are merged, and an empty range is a **conflict**;
    * anything else this module cannot combine is a **problem**.
    """
    if not isinstance(unconditional, dict):
        return Reading(problem=f"{where} bir nesne degil")

    unknown = _unknown_keys(unconditional, UNDERSTOOD_FIELD_KEYS)
    if unknown:
        return Reading(
            problem=f"{where} degerlendirilemeyen anahtar tasiyor: {', '.join(unknown)}"
        )

    extra = _constraints(unconditional)
    if not extra:
        return Reading(value=unconditional)

    outer_type, inner_type = extra.get("type"), conditional.get("type")
    if outer_type is not None and inner_type is not None and outer_type != inner_type:
        return Reading(
            conflict=(
                f"{where}.type ({outer_type!r}) kosullu tip ({inner_type!r}) ile "
                "ayni anda saglanamaz"
            )
        )

    outer_pattern, inner_pattern = extra.get("pattern"), conditional.get("pattern")
    if (
        outer_pattern is not None
        and inner_pattern is not None
        and outer_pattern != inner_pattern
    ):
        return Reading(
            problem=(
                f"{where}.pattern kosullu kaliptan farkli; iki kalibin kesisimi "
                "degerlendirilmedi"
            )
        )

    # Both levels bound the same string, so the effective range is the
    # intersection. An empty one is a demonstrated contradiction: no value
    # satisfies the schema, which means no signature would be accepted.
    lows = [
        bound
        for bound in (
            _bound(unconditional, "minLength"),
            _bound(conditional, "minLength"),
        )
        if bound is not None
    ]
    highs = [
        bound
        for bound in (
            _bound(unconditional, "maxLength"),
            _bound(conditional, "maxLength"),
        )
        if bound is not None
    ]
    if lows and highs and max(lows) > min(highs):
        return Reading(
            conflict=(
                f"{where} uzunluk araligi bos: en az {max(lows)}, en fazla "
                f"{min(highs)}; hicbir deger ikisini birden saglayamaz"
            )
        )

    return Reading(value=unconditional)


def _check_any_of(branches: object, payload_field: str) -> Reading:
    """``anyOf`` must leave a branch a signed body can actually satisfy.

    The reference publishes ``[{"required": ["from"]}, {"required": ["did"]}]``
    - name yourself or sign - and the signed branch is the one Station takes.
    That is the only shape read here. A branch shaped differently is not
    accepted merely for sitting inside a key called ``anyOf``: the previous
    version reasoned that ``anyOf`` could only add constraints, which is true
    and beside the point, because a constraint it adds can reject us.
    """
    if not isinstance(branches, list) or not branches:
        return Reading(problem="anyOf bos veya bir liste degil")

    accepted = frozenset({*_SIGNED_BODY_FIELDS, payload_field})
    satisfiable = False
    for index, branch in enumerate(branches):
        if not isinstance(branch, dict):
            return Reading(problem=f"anyOf[{index}] bir nesne degil")
        unknown = _unknown_keys(branch, UNDERSTOOD_BRANCH_KEYS)
        if unknown:
            return Reading(
                problem=(
                    f"anyOf[{index}] degerlendirilemeyen anahtar tasiyor: "
                    f"{', '.join(unknown)}"
                )
            )
        names = branch.get("required")
        if names is None:
            satisfiable = True  # an empty branch accepts anything
            continue
        if not isinstance(names, list) or not all(
            isinstance(name, str) for name in names
        ):
            return Reading(problem=f"anyOf[{index}].required bir ad listesi degil")
        if set(names) <= accepted:
            satisfiable = True

    if not satisfiable:
        return Reading(
            conflict=(
                "anyOf dallarindan hicbiri imzali govdenin tasidigi alanlarla "
                "saglanamiyor"
            )
        )
    return Reading(value=branches)


def evaluate_signed_body(schema: object, payload_field: str) -> Reading:
    """Read a request-body schema as a whole, or refuse to.

    Returns a :class:`SignedBodyView` when every part of the schema that bears
    on a signed write is one this module can read and none of them contradict.
    Otherwise a ``problem`` (cannot evaluate) or a ``conflict`` (evaluated, and
    impossible to satisfy).

    ``payload_field`` is ``text`` on the message lane and ``value`` on the note
    lane; both lanes go through here, so neither can quietly stop being
    checked.
    """
    if not isinstance(schema, dict):
        return Reading(problem="istek govdesi semasi bir nesne degil")

    unknown = _unknown_keys(schema, UNDERSTOOD_BODY_KEYS)
    if unknown:
        return Reading(
            problem=(
                "istek govdesi degerlendirilemeyen anahtar tasiyor: "
                f"{', '.join(unknown)}"
            )
        )

    properties = schema.get("properties")
    if not isinstance(properties, dict):
        return Reading(problem="istek govdesi properties bir nesne degil")

    if "anyOf" in schema:
        branches = _check_any_of(schema["anyOf"], payload_field)
        if branches.problem or branches.conflict:
            return branches

    dependent = schema.get("dependentSchemas")
    if dependent is None:
        return Reading(problem="imzali lane kosullu semasi yok (dependentSchemas eksik)")
    if not isinstance(dependent, dict):
        return Reading(problem="dependentSchemas bir nesne degil")

    lane = dependent.get("did")
    if lane is None:
        return Reading(problem="dependentSchemas.did yok")
    if not isinstance(lane, dict):
        return Reading(problem="dependentSchemas.did bir nesne degil")

    lane_unknown = _unknown_keys(lane, UNDERSTOOD_LANE_KEYS)
    if lane_unknown:
        return Reading(
            problem=(
                "dependentSchemas.did degerlendirilemeyen anahtar tasiyor: "
                f"{', '.join(lane_unknown)}"
            )
        )

    credentials = lane.get("properties")
    if not isinstance(credentials, dict):
        return Reading(problem="dependentSchemas.did.properties bir nesne degil")

    # Every field that decides whether a signed write is accepted: the two
    # credentials inside the conditional schema, the did that selects it, and
    # whatever the body says about the same names unconditionally.
    for name in ("sig", "nonce"):
        node = credentials.get(name)
        if node is None:
            return Reading(problem=f"dependentSchemas.did.properties.{name} yok")
        checked = _check_field_node(node, f"dependentSchemas.did.properties.{name}")
        if checked.problem or checked.conflict:
            return checked

        published = properties.get(name)
        if published is not None:
            assert isinstance(node, dict)
            reconciled = _reconcile(published, node, f"properties.{name}")
            if reconciled.problem or reconciled.conflict:
                return reconciled

    did_node = properties.get("did")
    if did_node is None:
        return Reading(problem="properties.did yok")
    did_checked = _check_field_node(did_node, "properties.did")
    if did_checked.problem or did_checked.conflict:
        return did_checked

    return Reading(value=SignedBodyView(body=schema, lane=lane, credentials=credentials))

