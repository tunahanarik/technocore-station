class _Absent:
    """Sentinel for "the document does not carry this".

    A distinct object rather than ``None`` because ``null`` is a value a
    server can legitimately publish, and the two must not be confused.
    """

    __slots__ = ()

    def __repr__(self) -> str:  # pragma: no cover - debugging aid
        return "<absent>"


ABSENT: Final = _Absent()


class DriftState(StrEnum):
    """The four states the manifest check can report."""

    #: No live check has run in this process. The starting state, every time.
    NEVER_CHECKED = "never_checked"
    #: Every critical field matches what Station signs for.
    CURRENT = "current"
    #: At least one critical field is present and differs. The gate closes.
    DRIFTED = "drifted"
    #: A required document could not be fetched or parsed, or a critical
    #: field could not be evaluated. The gate closes.
    UNAVAILABLE = "unavailable"


class Severity(StrEnum):
    CRITICAL = "critical"
    WARNING = "warning"


class FieldOutcome(StrEnum):
    """What happened to one field, distinguishing absence from difference."""

    MATCHED = "matched"
    #: Present, readable, and different. This is real drift.
    MISMATCH = "mismatch"
    #: The document does not carry the field at the documented pointer.
    MISSING = "missing"
    #: The document carries a schema shape this module cannot read safely.
    UNSUPPORTED = "unsupported"


class Compare(StrEnum):
    """How an observed value is judged against the expected one.

    Every mode is type-checked. ``"86"`` is not ``86``: a server that
    published the string would be publishing a different schema, and a
    comparison that stringified both would call them equal.
    """

    #: Exact string equality on the original value. No sweeping, no
    #: stripping: a trailing newline is a different canonical payload.
    TEXT = "text"
    #: Exact integer equality. ``bool`` is rejected explicitly - it is an
    #: ``int`` subclass, and ``True == 1``.
    NUMBER = "number"
    #: The expected string must appear in a JSON array of strings.
    MEMBER = "member"
    #: A JSON array of strings whose set equals the expected set. Used for
    #: conditional ``required``, where order carries no meaning.
    NAME_SET = "name_set"
    #: A bounded prose check: every machine token present, no negation
    #: marker anywhere. See :data:`NEGATION_MARKERS`.
    PROSE = "prose"


class Lane(StrEnum):
    """Which sub-document a field's pointer is relative to."""

    #: The document root.
    DOCUMENT = "document"
    #: The message POST request-body schema.
    MESSAGE_BODY = "message_body"
    #: The note POST request-body schema.
    NOTE_BODY = "note_body"
    #: The subschema that applies to a message body *once it carries a did*.
    MESSAGE_SIGNED = "message_signed"
    #: The same, for a note body.
